-- 1. Create the events table
create table if not exists events (
  id            bigint generated by default as identity primary key,
  title         text not null,
  category      text not null,   -- see EVENT_CATEGORIES in lib/events.js for valid ids
  date          date not null,   -- start date
  end_date      date,            -- optional, for multi-day events
  time_label    text,            -- display string, e.g. "7:00 PM – 10:00 PM"
  venue         text not null,
  city          text not null,
  link          text,            -- IG post, Eventbrite, or org site (optional)
  flier_url     text,            -- hosted flier image (optional)
  description   text,            -- optional
  contact_email text,            -- submitter contact — PRIVATE, never shown on site
  approved      boolean not null default false,
  created_at    timestamptz not null default now()
);

-- 2. Enable Row Level Security
alter table events enable row level security;

-- 3. Public can READ approved events only
create policy "Public can read approved events"
  on events for select
  using (approved = true);

-- 4. Anyone can SUBMIT an event (always lands unapproved)
create policy "Anyone can submit an event"
  on events for insert
  with check (approved = false);

-- 5. Keep contact_email private: column-level grant so the anon key
--    can never read it, even on approved rows.
--    NOTE: app queries must select explicit columns (not *) after this.
revoke select on table events from anon, authenticated;
grant select (id, title, category, date, end_date, time_label, venue, city,
              link, flier_url, description, approved, created_at)
  on events to anon, authenticated;

